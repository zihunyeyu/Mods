DROP TABLE IF EXISTS TRM_Numbers;
CREATE TABLE "TRM_Numbers" (
'No' INTEGER NOT NULL,
PRIMARY KEY(No)
);
WITH RECURSIVE
  INDICES(i) AS (SELECT 1 UNION ALL SELECT (i + 1) FROM INDICES LIMIT 100)
  INSERT INTO TRM_Numbers(No) select i from INDICES;

INSERT INTO Modifiers(ModifierId, ModifierType, SubjectRequirementSetId)
SELECT 
    'MODIFIER_TRM_ADD_YIELD_FOR_IN_COMING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 
    'MODIFIER_SINGLE_CITY_ADJUST_YIELD_CHANGE', 
    NULL
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_IN_COMING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'Amount', TRM_Numbers.No
FROM TRM_Numbers
CROSS JOIN Yields
UNION SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_IN_COMING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No,'YieldType',Yields.YieldType
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO Modifiers(ModifierId, ModifierType, SubjectRequirementSetId)
SELECT 
    'MODIFIER_TRM_ADD_YIELD_FOR_OUT_GOING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 
    'MODIFIER_SINGLE_CITY_ADJUST_YIELD_CHANGE', 
    NULL
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_OUT_GOING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'Amount', TRM_Numbers.No
FROM TRM_Numbers
CROSS JOIN Yields
UNION SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_OUT_GOING_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No,'YieldType',Yields.YieldType
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO RequirementSets (RequirementSetId, RequirementSetType)
SELECT 'REQS_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'REQUIREMENTSET_TEST_ALL'
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO RequirementSetRequirements (RequirementSetId, RequirementId)
SELECT 'REQS_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'REQ_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO Requirements (RequirementId, RequirementType)
SELECT 'REQ_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'REQUIREMENT_PLOT_PROPERTY_MATCHES'
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO RequirementArguments (RequirementId, Name, Value)
SELECT 'REQ_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'PropertyName', 'PROPERTY_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No
FROM TRM_Numbers
CROSS JOIN Yields
UNION SELECT 'REQ_TRM_ADD_YIELD_FOR_FOR_TRADE_CITY_'||Yields.YieldType||TRM_Numbers.No, 'PropertyMinimum', 1
FROM TRM_Numbers
CROSS JOIN Yields;

INSERT INTO Modifiers(ModifierId, ModifierType, SubjectRequirementSetId)
SELECT 
    'MODIFIER_TRM_ADD_YIELD_FOR_TRADE_CITY_DECIMAL_'||Yields.YieldType||TRM_Numbers.No, 
    'MODIFIER_SINGLE_CITY_ADJUST_YIELD_CHANGE', 
    NULL
FROM Yields
INNER JOIN TRM_Numbers ON TRM_Numbers.No > 0 AND TRM_Numbers.No < 10;

INSERT INTO ModifierArguments (ModifierId, Name, Value)
SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_TRADE_CITY_DECIMAL_'||Yields.YieldType||TRM_Numbers.No, 'Amount', '0.'||TRM_Numbers.No
FROM Yields
INNER JOIN TRM_Numbers ON TRM_Numbers.No > 0 AND TRM_Numbers.No < 10
UNION SELECT 'MODIFIER_TRM_ADD_YIELD_FOR_TRADE_CITY_DECIMAL_'||Yields.YieldType||TRM_Numbers.No,'YieldType',Yields.YieldType
FROM Yields
INNER JOIN TRM_Numbers ON TRM_Numbers.No > 0 AND TRM_Numbers.No < 10;


CREATE TABLE "TRM_TraitTradeRouteModifier" (
TraitType TEXT NOT NULL,
TradeRouteModifier TEXT NOT NULL,
FOREIGN KEY(TraitType) REFERENCES Traits(TraitType),
FOREIGN KEY(TradeRouteModifier) REFERENCES TRM_TradeRouteModifier(TradeRouteModifier)
);

-- =================
CREATE TABLE "TRM_TradeRouteModifier" (
TradeRouteModifier TEXT NOT NULL,
Name TEXT DEFAULT NULL,
TradeRouteDirection INTEGER DEFAULT 0,
BenefitCity INTEGER DEFAULT 0,
TradeRouteType INTEGER DEFAULT 0,
PRIMARY KEY(TradeRouteModifier)
);

CREATE TABLE "TRM_TradeRouteModifierArguments" (
TradeRouteModifier TEXT NOT NULL,
Name TEXT NOT NULL,
Value TEXT NOT NULL,
FOREIGN KEY(TradeRouteModifier) REFERENCES TRM_TradeRouteModifier(TradeRouteModifier)
);

CREATE TABLE "TRM_TradeRouteModifierFilters" (
Filter TEXT NOT NULL,
FilterType TEXT NOT NULL,
Name TEXT NOT NULL,
Value TEXT NOT NULL
);

CREATE TABLE "TRM_TradeRouteModifierRequirements" (
Requirement TEXT NOT NULL,
RequirementType TEXT NOT NULL,
Name TEXT NOT NULL,
Value TEXT NOT NULL,
Inverse BOOLEAN NOT NULL DEFAULT 0
);

