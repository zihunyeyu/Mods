INSERT OR IGNORE INTO TKH_UnitTypeArmor(UnitType, BaseArmor)
SELECT TypeTags.Type, TKH_UnitTagArmor.BaseArmor
FROM TypeTags INNER JOIN TKH_UnitTagArmor ON 
    TypeTags.Type IN (SELECT UnitType FROM Units) AND 
    TypeTags.Tag IN (SELECT Tag FROM TKH_UnitTagArmor) AND 
    TKH_UnitTagArmor.Tag = TypeTags.Tag;


