INSERT INTO TypeTags(Type, Tag)
WITH split(Name,splid,idsstr) AS
(
  SELECT  Name,'',Heroes||',' FROM TKH_RelationshipAbilities
  UNION ALL 
   SELECT Name,substr(idsstr, 0, instr(idsstr, ',')),substr(idsstr, instr(idsstr, ',')+1)
    FROM split WHERE idsstr!=''
)
SELECT 
    'ABILITY_RELATIONSHIP_'||Name||'_'||splid,
    -- 核心条件判断：存在则用原标识，不存在则替换为UNIT版本
    CASE 
        WHEN EXISTS (SELECT 1 FROM Tags WHERE Tag = 'CLASS_HERO_TKH_'||splid) 
        THEN 'CLASS_HERO_TKH_'||splid
        ELSE 'CLASS_UNIT_HERO_TKH_'||splid
    END
FROM split WHERE splid != ''
UNION 
SELECT 
    'ABILITY_MODIFIER_ABILITY_RELATIONSHIP_'||Name||'_'||splid,
    -- 第二处同逻辑的条件判断
    CASE 
        WHEN EXISTS (SELECT 1 FROM Tags WHERE Tag = 'CLASS_HERO_TKH_'||splid) 
        THEN 'CLASS_HERO_TKH_'||splid
        ELSE 'CLASS_UNIT_HERO_TKH_'||splid
    END
FROM split WHERE splid != '';


