INSERT OR REPLACE INTO Modifiers (ModifierId, ModifierType, Permanent)
SELECT UnitPromotionType||'_ALL_PLAYERS_ATTACH', 'MODIFIER_ALL_PLAYERS_ATTACH_MODIFIER', 1
FROM UnitPromotions WHERE UnitPromotionType LIKE 'PROMOTION_TK_%'
UNION SELECT UnitPromotionType||'_REPROMOTION', 'MODIFIER_PLAYER_UNITS_GRANT_PROMOTION', 1
FROM UnitPromotions WHERE UnitPromotionType LIKE 'PROMOTION_TK_%';

